// 掃原始碼用的小工具（沿用 StockDiary）。
//
// 稽核「程式碼裡有沒有 X」時，註解裡的 X 不算數（不然等於罰人寫註解），
// 而**網址裡的 `//` 也不是註解**。判斷方式：`//` 前面緊接著 `:` 就是網址的一部分。
//
// 這不是完整的 JS 剖析器 —— 對「稽核原始碼有沒有出現某個字串」這個用途夠用，
// 而且寧可少剝也不要多剝。shelltest 對它有對照組。

export function stripComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}
